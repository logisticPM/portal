import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import { EVAL_QUERIES } from "../src/lib/cases/validate/eval-queries";
import type { GoldQuery } from "../src/lib/cases/validate/retrieval";

const LAYERS = new Set(["known_item", "conceptual", "topical"]);

// every query has a valid layer + unique qid
const qids = new Set<string>();
for (const q of EVAL_QUERIES) {
  assert.ok(LAYERS.has(q.layer), `bad layer: ${q.layer}`);
  assert.ok(!qids.has(q.qid), `dup qid: ${q.qid}`);
  qids.add(q.qid);
}
assert.ok(EVAL_QUERIES.some((q) => q.layer === "known_item"), "has known_item");
assert.ok(EVAL_QUERIES.some((q) => q.layer === "conceptual"), "has conceptual");
assert.ok(EVAL_QUERIES.some((q) => q.layer === "topical"), "has topical");

(async () => {
  const text = await fs.readFile("docs/research/gold/cases-retrieval-gold.jsonl", "utf8");
  const gold = text.trim().split(/\n+/).filter(Boolean).map((l) => JSON.parse(l) as GoldQuery);

  // every gold line parses, its qid exists in EVAL_QUERIES, judgments are non-empty,
  // each caseId is a non-empty slug, and grades are 0/1/2. (Gold references real
  // corpus ids — slugified citations — not just the seed fixtures.)
  const qseen = new Set<string>();
  for (const g of gold) {
    assert.ok(qids.has(g.qid), `gold qid not in EVAL_QUERIES: ${g.qid}`);
    qseen.add(g.qid);
    assert.ok(g.judgments.length > 0, `gold ${g.qid} has no judgments`);
    for (const j of g.judgments) {
      assert.ok(typeof j.caseId === "string" && j.caseId.length > 0, `bad caseId in ${g.qid}`);
      assert.ok([0, 1, 2].includes(j.rel), `bad grade: ${j.rel}`);
    }
  }
  // Every query is covered by the gold. Reports the FULL gap rather than throwing on the first
  // uncovered qid: during the wave-C expansion this check is legitimately red from the moment the
  // query set grows until the judging run regenerates the gold, and every implementer in between
  // runs this suite. "no gold for query conceptual-007" tells them nothing about whether they
  // broke something; a list plus the reason tells them at a glance that it is the known gap.
  //
  // Still a hard failure — the invariant is real. Only the diagnostics changed.
  const uncovered = EVAL_QUERIES.filter((q) => !qseen.has(q.qid)).map((q) => q.qid);
  assert.equal(uncovered.length, 0,
    `${uncovered.length} of ${EVAL_QUERIES.length} queries have no gold: ${uncovered.join(", ")}\n` +
    `  The gold is REGENERATED by the judging run (scripts/cases-judge-pool.ts), never hand-edited.\n` +
    `  Until that runs, this failure is expected. Do not add placeholder gold to make it green.`);

  // --- wave C: the set is 50, layered, and every entry is distinct --------------------------
  {
    // 50 is not decorative: the spec sizes the paired bootstrap against it, and a layer that
    // silently lost entries would make its per-layer mean a different measurement than the
    // report claims.
    assert.equal(EVAL_QUERIES.length, 50, "the eval surface is 50 queries — changing it changes what every number means");
    const byLayer = (l: string) => EVAL_QUERIES.filter((q) => q.layer === l).length;
    assert.equal(byLayer("known_item"), 17, "known_item layer size");
    assert.equal(byLayer("conceptual"), 17, "conceptual layer size");
    assert.equal(byLayer("topical"), 16, "topical layer size");
    assert.equal(byLayer("known_item") + byLayer("conceptual") + byLayer("topical"), EVAL_QUERIES.length,
      "every query is in one of the three layers — an unknown layer would vanish from the per-layer report");

    // A duplicate qid silently overwrites in any Map keyed by it, including the gold loader's.
    const qids = EVAL_QUERIES.map((q) => q.qid);
    assert.equal(new Set(qids).size, qids.length, "qids must be unique");
    // A duplicate query string would be judged twice and counted twice, weighting it double.
    const texts = EVAL_QUERIES.map((q) => q.query.trim().toLowerCase());
    assert.equal(new Set(texts).size, texts.length, "query strings must be unique");

    // Shape sanity per layer. known_item is a lookup string; conceptual is a sentence. A conceptual
    // query that is three words long is a topical query wearing the wrong label, and it would be
    // scored as evidence that dense retrieval helps on conceptual queries.
    for (const q of EVAL_QUERIES.filter((x) => x.layer === "known_item"))
      assert.ok(q.query.length <= 60, `known_item query is too long to be a lookup: ${q.qid}`);
    for (const q of EVAL_QUERIES.filter((x) => x.layer === "conceptual"))
      assert.ok(q.query.length >= 40, `conceptual query is too short to be a plain-language question: ${q.qid}`);
  }

  console.log(`✅ eval-queries + gold consistent (${EVAL_QUERIES.length} queries, ${gold.length} gold)`);
})().catch((e) => { console.error("❌ test failed:", e); process.exit(1); });
